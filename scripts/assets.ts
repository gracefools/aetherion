// Asset import validation. Art from outside the code base only becomes game-ready if it passes
// every check here: naming, dimensions, transparency, frames, directions and layer alignment.
// Used by the CLI (scripts/validate-assets.ts), the client build, and the tests.
import fs from 'node:fs';
import path from 'node:path';
import { ANIM_COL, ANIMS, FRAME_H, FRAME_W, SHEET_COLS, type Anim } from '../shared/src/appearance';
import { MONSTERS } from '../shared/src/monsters';
import { ABILITIES, ELEMENTS } from '../shared/src/abilities';
import { STATUS } from '../shared/src/combat';
import { ITEMS } from '../shared/src/items';
import { JOB_DEFS } from '../shared/src/jobs';
import { JOBS } from '../shared/src/protocol';
import { decodePng, type Image } from './png';

export const LAYERS = ['body', 'clothing', 'armor', 'face', 'hair', 'helmet', 'accessory', 'cape', 'weapon'] as const;
export const PROPS = ['iron_ore', 'moonleaf', 'star_shard', 'cache', 'cache_open', 'waystone'];
/** Monster sheets: idle 2, move 4, attack 3, hit 1, death 3 = 13 columns; row 0 faces right, row 1 left. */
export const M_COLS = 13, M_ROWS = 2, M_FRAME = 48;
const M_ANIM: [string, number, number][] = [['idle', 0, 2], ['move', 2, 4], ['attack', 6, 3], ['hit', 9, 1], ['death', 10, 3]];
const FEET_ROW = FRAME_H - 4; // characters stand on this pixel row
const NAME = /^[a-z0-9]+(_[a-z0-9]+)*$/;

/** Where an asset came from and what may be done with it. Required for every new asset type. */
export interface AssetMeta {
  /** Who or what made it: an artist, a tool and prompt, "generated by code". */
  source?: string;
  /** Usage rights as far as they are actually known. */
  license?: string;
}
export const ICON_KINDS = ['skill', 'passive', 'status', 'attack', 'rune', 'item'] as const;
export type IconKind = (typeof ICON_KINDS)[number];
export const NPC_KINDS = ['merchant', 'waykeeper', 'lorekeeper', 'runesmith'];
export const TILESET_THEMES = ['kingdom', 'forest', 'ashen', 'frost', 'moor', 'astral', 'ruins', 'lair', 'citadel', 'temple'];
export type SheetEntry = (
  | { type: 'monster'; id: string; file: string; scale?: number }
  | { type: 'prop'; id: string; file: string }
  | { type: 'character'; layer: (typeof LAYERS)[number]; item: string; file: string }
  // M12: icons (64x64, or 16x16 for item icons), NPC sheets (a full character sheet), tilesets and effect strips
  | { type: 'icon'; kind: IconKind; id: string; file: string }
  | { type: 'npc'; id: string; file: string }
  | { type: 'tileset'; id: string; file: string; tile?: number }
  | { type: 'vfx'; id: string; file: string; frameW: number; frameH: number; frames: number; fps: number }
) & AssetMeta;
export const ENTRY_TYPES = ['monster', 'prop', 'character', 'icon', 'npc', 'tileset', 'vfx'];
/** The id of an entry, unique within its type: what the game looks it up by. */
export const entryKey = (e: SheetEntry) => (e.type === 'character' ? `character/${e.layer}/${e.item}` : e.type === 'icon' ? `icon/${e.kind}/${e.id}` : `${e.type}/${e.id}`);
/** Whether an icon id names something that exists in the game data. */
export function iconKnown(kind: IconKind, id: string): boolean {
  switch (kind) {
    case 'skill': return !!ABILITIES[id];
    case 'passive': return JOBS.some((j) => JOB_DEFS[j].skills.some((s) => s.id === id && s.type === 'passive') || JOB_DEFS[j].passives.some((p) => p.id === id));
    case 'status': return STATUS.some((s) => s.id === id);
    case 'attack': return JOBS.some((j) => JOB_DEFS[j].weapons.some((w) => w.kind === id));
    case 'rune': return (ELEMENTS as readonly string[]).includes(id);
    case 'item': return !!ITEMS[id];
  }
}

/** Everything the game needs to know about an imported asset, derived from the entry and the image. */
export interface AssetRecord {
  id: string;
  type: string;
  file: string;
  width: number;
  height: number;
  frameWidth: number;
  frameHeight: number;
  /** Animation names in sheet order, with their frame counts. */
  animations: Record<string, number>;
  /** What each row of the sheet faces. */
  directions: string[];
  /** Drawing order among character layers (0 = bottom); -1 for assets that are not layers. */
  layerOrder: number;
  /** The pixel within a frame that sits on the entity's position. */
  anchor: [number, number];
  /** True if the image has fully transparent pixels. */
  transparent: boolean;
  fps: number;
  /** The character, class, monster or skill it belongs to. */
  associated: string;
  source: string;
  license: string;
}
/** Builds the full metadata record of a validated entry, so nobody has to write it by hand. */
export function describe(e: SheetEntry, img: Image): AssetRecord {
  let transparent = false;
  for (let i = 3; i < img.data.length && !transparent; i += 4) if (!img.data[i]) transparent = true;
  const base = { id: entryKey(e), type: e.type, file: e.file, width: img.w, height: img.h, transparent, source: e.source ?? '', license: e.license ?? '' };
  if (e.type === 'monster') {
    const f = Math.round(M_FRAME * (e.scale ?? 1));
    return { ...base, frameWidth: f, frameHeight: f, animations: Object.fromEntries(M_ANIM.map(([n, , k]) => [n, k])), directions: ['right', 'left'], layerOrder: -1, anchor: [f / 2, Math.round(42 * (e.scale ?? 1))], fps: 8, associated: `monster:${e.id}` };
  }
  if (e.type === 'character' || e.type === 'npc') {
    const anims = Object.fromEntries((Object.keys(ANIMS) as Anim[]).map((n) => [n, ANIMS[n].frames]));
    return { ...base, frameWidth: FRAME_W, frameHeight: FRAME_H, animations: anims, directions: ['down', 'left', 'right', 'up'], layerOrder: e.type === 'character' ? LAYERS.indexOf(e.layer) : -1, anchor: [FRAME_W / 2, FEET_ROW], fps: 8, associated: e.type === 'character' ? `item:${e.item}` : `npc:${e.id}` };
  }
  if (e.type === 'vfx') return { ...base, frameWidth: e.frameW, frameHeight: e.frameH, animations: { play: e.frames }, directions: [], layerOrder: -1, anchor: [e.frameW / 2, e.frameH / 2], fps: e.fps, associated: `effect:${e.id}` };
  if (e.type === 'tileset') {
    const t = e.tile ?? 32;
    return { ...base, frameWidth: t, frameHeight: t, animations: {}, directions: [], layerOrder: -1, anchor: [0, 0], fps: 0, associated: `theme:${e.id}` };
  }
  if (e.type === 'icon') return { ...base, frameWidth: img.w, frameHeight: img.h, animations: {}, directions: [], layerOrder: -1, anchor: [0, 0], fps: 0, associated: `${e.kind}:${e.id}` };
  return { ...base, frameWidth: 32, frameHeight: 32, animations: {}, directions: [], layerOrder: -1, anchor: [16, 28], fps: 0, associated: `object:${e.id}` };
}

/** Rules for the M12 asset types. */
function validateExtra(e: Extract<SheetEntry, { type: 'icon' | 'npc' | 'tileset' | 'vfx' }>, img: Image, add: (level: Finding['level'], rule: Finding['rule'], msg: string) => void) {
  const base = path.basename(e.file, '.png'), dir = path.dirname(e.file).split(path.sep).join('/');
  if (!NAME.test(base)) add('error', 'naming', `"${base}" must be lower_snake_case (a-z, 0-9, single underscores)`);
  if (base !== e.id) add('error', 'naming', `file name "${base}" must equal the id "${e.id}"`);
  if (!e.source?.trim()) add('error', 'metadata', 'missing "source" (who or what made this asset)');
  if (!e.license?.trim()) add('error', 'metadata', 'missing "license" (the usage rights, as far as they are known)');
  let opaque = 0, clear = 0;
  for (let i = 3; i < img.data.length; i += 4) img.data[i] === 255 ? opaque++ : img.data[i] === 0 && clear++;
  if (e.type === 'icon') {
    if (!ICON_KINDS.includes(e.kind)) return void add('error', 'naming', `unknown icon kind "${e.kind}" (${ICON_KINDS.join(', ')})`);
    if (dir !== `icons/${e.kind}`) add('error', 'naming', `must be in the "icons/${e.kind}/" folder, found "${dir}/"`);
    if (!iconKnown(e.kind, e.id)) add('error', 'naming', `"${e.id}" is not a known ${e.kind} in the game data`);
    const sizes = e.kind === 'item' ? [16, 32, 64] : [64, 96];
    if (img.w !== img.h || !sizes.includes(img.w)) return void add('error', 'dimensions', `icon is ${img.w}x${img.h}, expected a square of ${sizes.join(' or ')} pixels`);
    if (!clear) add('error', 'transparency', 'no transparent pixels: an icon needs a transparent background (at least its corners)');
    if (opaque < img.w * img.h * 0.1) add('error', 'frames', 'the icon is empty or almost empty');
    for (const [x, y] of [[0, 0], [img.w - 1, 0], [0, img.h - 1], [img.w - 1, img.h - 1]]) if (alpha(img, x, y) === 255) { add('error', 'transparency', 'the corners of an icon must be transparent'); break; }
  } else if (e.type === 'tileset') {
    const t = e.tile ?? 32;
    if (dir !== 'tilesets') add('error', 'naming', `must be in the "tilesets/" folder, found "${dir}/"`);
    if (!TILESET_THEMES.includes(e.id)) add('error', 'naming', `"${e.id}" is not a map theme (${TILESET_THEMES.join(', ')})`);
    if (t !== 16 && t !== 32) add('error', 'dimensions', `tile size ${t} is not supported (16 or 32)`);
    else if (img.w % t || img.h % t || img.w < t * 4) add('error', 'dimensions', `tileset is ${img.w}x${img.h}: it must be a grid of ${t}x${t} tiles, at least 4 tiles wide`);
  } else if (e.type === 'vfx') {
    if (dir !== 'vfx') add('error', 'naming', `must be in the "vfx/" folder, found "${dir}/"`);
    if (![e.frameW, e.frameH, e.frames, e.fps].every((v) => Number.isInteger(v) && v > 0)) return void add('error', 'metadata', 'an effect needs frameW, frameH, frames and fps (positive whole numbers)');
    if (e.fps > 60) add('error', 'metadata', `${e.fps} frames per second is more than the game draws`);
    if (img.w !== e.frameW * e.frames || img.h !== e.frameH) return void add('error', 'dimensions', `strip is ${img.w}x${img.h}, expected ${e.frameW * e.frames}x${e.frameH} (${e.frames} frames of ${e.frameW}x${e.frameH} in one row)`);
    if (!clear) add('error', 'transparency', 'no transparent pixels: the background must be transparent');
    for (let k = 0; k < e.frames; k++) if (frameInfo(img, k * e.frameW, 0, e.frameW, e.frameH).n === 0 && k < e.frames - 1) add('error', 'frames', `frame ${k} is empty`);
    if (e.frames > 1 && sameFrame(img, 0, 0, e.frameW, 0, e.frameW, e.frameH)) add('warning', 'frames', 'the first two frames are identical: is this an animation?');
  } else {
    if (dir !== 'npcs') add('error', 'naming', `must be in the "npcs/" folder, found "${dir}/"`);
    if (!NPC_KINDS.includes(e.id)) add('error', 'naming', `"${e.id}" is not an NPC role (${NPC_KINDS.join(', ')})`);
    if (img.w !== SHEET_COLS * FRAME_W || img.h !== 4 * FRAME_H) return void add('error', 'dimensions', `sheet is ${img.w}x${img.h}, expected ${SHEET_COLS * FRAME_W}x${4 * FRAME_H} (${SHEET_COLS} columns x 4 rows of ${FRAME_W}x${FRAME_H})`);
    if (!clear) add('error', 'transparency', 'no transparent pixels: the background must be transparent');
    for (let r = 0; r < 4; r++) if (frameInfo(img, 0, r * FRAME_H, FRAME_W, FRAME_H).n < 20) add('error', 'direction', `row ${r} (${['down', 'left', 'right', 'up'][r]}) is missing: an NPC needs all four directions`);
    if (sameFrame(img, 0, FRAME_H, 0, 2 * FRAME_H, FRAME_W, FRAME_H)) add('error', 'direction', 'row 1 (left) is identical to row 2 (right): one must be the mirror of the other');
  }
}
export interface Manifest {
  version: 1;
  sheets: SheetEntry[];
}
export interface Finding {
  file: string;
  level: 'error' | 'warning';
  rule: 'naming' | 'dimensions' | 'transparency' | 'frames' | 'direction' | 'alignment' | 'manifest' | 'format' | 'metadata';
  msg: string;
}

const alpha = (img: Image, x: number, y: number) => img.data[(y * img.w + x) * 4 + 3];
/** Opaque-pixel count and bounding box of one frame. */
function frameInfo(img: Image, fx: number, fy: number, fw: number, fh: number) {
  let n = 0, x0 = fw, y0 = fh, x1 = -1, y1 = -1, soft = 0;
  for (let y = 0; y < fh; y++)
    for (let x = 0; x < fw; x++) {
      const a = alpha(img, fx + x, fy + y);
      if (!a) continue;
      if (a < 255) soft++;
      n++;
      if (x < x0) x0 = x;
      if (x > x1) x1 = x;
      if (y < y0) y0 = y;
      if (y > y1) y1 = y;
    }
  return { n, x0, y0, x1, y1, soft };
}
function sameFrame(img: Image, ax: number, ay: number, bx: number, by: number, fw: number, fh: number, mirror = false) {
  for (let y = 0; y < fh; y++)
    for (let x = 0; x < fw; x++) {
      const i = ((ay + y) * img.w + ax + x) * 4, j = ((by + y) * img.w + bx + (mirror ? fw - 1 - x : x)) * 4;
      if (img.data[i + 3] !== img.data[j + 3]) return false;
      if (img.data[i + 3] && (img.data[i] !== img.data[j] || img.data[i + 1] !== img.data[j + 1] || img.data[i + 2] !== img.data[j + 2])) return false;
    }
  return true;
}

/** Checks one decoded sheet against the rules for its type. */
export function validateSheet(e: SheetEntry, img: Image): Finding[] {
  const out: Finding[] = [], add = (level: Finding['level'], rule: Finding['rule'], msg: string) => out.push({ file: e.file, level, rule, msg });
  if (!e.file.toLowerCase().endsWith('.png')) add('error', 'format', `unsupported format "${path.extname(e.file) || 'none'}": images must be PNG`);
  if (e.type === 'icon' || e.type === 'npc' || e.type === 'tileset' || e.type === 'vfx') {
    validateExtra(e, img, add);
    return out;
  }
  // ---- naming ----
  const base = path.basename(e.file, '.png'), dir = path.dirname(e.file).split(path.sep).join('/');
  if (!NAME.test(base)) add('error', 'naming', `"${base}" must be lower_snake_case (a-z, 0-9, single underscores)`);
  const wantDir = e.type === 'monster' ? 'monsters' : e.type === 'prop' ? 'props' : e.layer;
  if (dir !== wantDir) add('error', 'naming', `must be in the "${wantDir}/" folder, found "${dir}/"`);
  if (e.type === 'character') {
    if (!LAYERS.includes(e.layer)) add('error', 'naming', `unknown layer "${e.layer}"`);
    if (base !== e.item) add('error', 'naming', `file name "${base}" must equal the item id "${e.item}"`);
  } else {
    if (base !== e.id) add('error', 'naming', `file name "${base}" must equal the id "${e.id}"`);
    if (e.type === 'monster' && !MONSTERS[e.id]) add('error', 'naming', `"${e.id}" is not a monster in the game data`);
    if (e.type === 'prop' && !PROPS.includes(e.id)) add('error', 'naming', `"${e.id}" is not a known prop (${PROPS.join(', ')})`);
  }
  // ---- dimensions ----
  let fw = FRAME_W, fh = FRAME_H, cols = SHEET_COLS, rows = 4;
  if (e.type === 'monster') {
    const sc = e.scale ?? 1;
    fw = fh = Math.round(M_FRAME * sc);
    cols = M_COLS;
    rows = M_ROWS;
    if (!(sc >= 0.5 && sc <= 3)) add('error', 'dimensions', `scale ${sc} is outside 0.5 to 3`);
  } else if (e.type === 'prop') {
    fw = fh = 32;
    cols = rows = 1;
  }
  if (img.w !== cols * fw || img.h !== rows * fh) {
    add('error', 'dimensions', `sheet is ${img.w}x${img.h}, expected ${cols * fw}x${rows * fh} (${cols} columns x ${rows} rows of ${fw}x${fh})`);
    return out; // nothing else can be checked on a sheet of the wrong size
  }
  // ---- transparency ----
  let opaque = 0, soft = 0;
  for (let i = 3; i < img.data.length; i += 4) {
    if (img.data[i] === 255) opaque++;
    else if (img.data[i]) soft++;
  }
  const total = img.w * img.h;
  if (opaque === total) add('error', 'transparency', 'no transparent pixels: the background must be transparent, not a flat colour');
  else if (opaque > total * 0.75) add('error', 'transparency', `${Math.round((opaque / total) * 100)}% of the sheet is opaque: the background was probably not removed`);
  for (const [x, y] of [[0, 0], [img.w - 1, 0], [0, img.h - 1], [img.w - 1, img.h - 1]]) if (alpha(img, x, y)) { add('error', 'transparency', 'the corners of the sheet must be transparent'); break; }
  // Pixel art has hard edges. Death frames may fade out; anything else semi-transparent is anti-aliasing.
  let softAllowed = 0;
  if (e.type === 'monster') for (let r = 0; r < rows; r++) softAllowed += frameInfo(img, 12 * fw, r * fh, fw, fh).soft;
  if (e.type === 'character') {
    // death fades out; weapons may carry translucent swing arcs and spell glows in attack and cast frames
    const fading: Anim[] = e.layer === 'weapon' ? ['death', 'attack', 'cast'] : ['death'];
    for (const an of fading) for (let r = 0; r < rows; r++) for (let k = 0; k < ANIMS[an].frames; k++) softAllowed += frameInfo(img, (ANIM_COL[an] + k) * fw, r * fh, fw, fh).soft;
  }
  if (soft - softAllowed > 0) add(soft - softAllowed > total * 0.002 ? 'error' : 'warning', 'transparency', `${soft - softAllowed} semi-transparent pixels: export without anti-aliasing (alpha must be 0 or 255)`);
  // ---- frames ----
  const info = (c: number, r: number) => frameInfo(img, c * fw, r * fh, fw, fh);
  if (e.type === 'prop') {
    const f = info(0, 0);
    if (f.n < 24) add('error', 'frames', 'the sprite is empty or too small to see');
    if (f.y1 < 22) add('warning', 'alignment', `the sprite floats: its lowest pixel is on row ${f.y1}, expected near the bottom (row 24 to 31)`);
    return out;
  }
  const anims: [string, number, number][] = e.type === 'monster' ? M_ANIM : (Object.keys(ANIMS) as Anim[]).map((name) => [name, ANIM_COL[name], ANIMS[name].frames]);
  // Layers such as capes or weapons may be hidden in some frames; the body and whole monsters may not.
  const mustFill = e.type === 'monster' || e.layer === 'body';
  for (let r = 0; r < rows; r++)
    for (let c = 0; c < cols; c++) {
      const f = info(c, r);
      if (mustFill && f.n < 20) add('error', 'frames', `frame ${c}/${r} is empty`);
      if (f.n && (f.x0 === 0 || f.x1 === fw - 1 || f.y0 === 0) && e.type === 'character') add('warning', 'frames', `frame ${c}/${r} touches the frame edge: the sprite may be cut off`);
    }
  for (let r = 0; r < rows; r++) {
    for (const [name, col, n] of anims) {
      if (name === 'idle' || !mustFill) continue;
      let moves = false;
      for (let k = 0; k < n; k++) if (!sameFrame(img, 0, r * fh, (col + k) * fw, r * fh, fw, fh)) moves = true;
      if (!moves) add('error', 'frames', `row ${r}: the ${name} animation is identical to the idle frame`);
    }
    if (mustFill)
      for (const [name, col, n] of anims) {
        if (n < 3) continue;
        let distinct = false;
        for (let k = 1; k < n; k++) if (!sameFrame(img, col * fw, r * fh, (col + k) * fw, r * fh, fw, fh)) distinct = true;
        if (!distinct) add('error', 'frames', `row ${r}: all ${n} frames of ${name} are the same picture`);
      }
  }
  // ---- direction ----
  if (e.type === 'monster') {
    if (sameFrame(img, 0, 0, 0, fh, fw, fh)) add('error', 'direction', 'row 1 (facing left) is identical to row 0 (facing right): mirror it or draw it');
  } else if (mustFill) {
    // a bare body can look the same from front and back (the face is its own layer), so this is only a warning
    if (sameFrame(img, 0, 0, 0, 3 * fh, fw, fh)) add('warning', 'direction', 'row 3 (facing up) is identical to row 0 (facing down)');
    if (sameFrame(img, 0, fh, 0, 2 * fh, fw, fh)) add('error', 'direction', 'row 1 (left) is identical to row 2 (right): one must be the mirror of the other');
    else if (!sameFrame(img, 0, fh, 0, 2 * fh, fw, fh, true)) add('warning', 'direction', 'row 1 (left) is not an exact mirror of row 2 (right); allowed, but check that it is intended');
  }
  // ---- alignment ----
  if (e.type === 'monster') {
    const base42 = Math.round(42 * (e.scale ?? 1));
    for (let r = 0; r < rows; r++) {
      const f = info(0, r);
      if (f.n && (f.y1 > base42 + Math.ceil(3 * (e.scale ?? 1)) || (!MONSTERS[e.id]?.flying && f.y1 < base42 - Math.ceil(8 * (e.scale ?? 1)))))
        add('error', 'alignment', `row ${r}: the lowest pixel of the idle frame is on row ${f.y1}; the ground line is row ${base42}`);
      const mid = (f.x0 + f.x1) / 2;
      if (f.n && Math.abs(mid - fw / 2) > fw * 0.2) add('warning', 'alignment', `row ${r}: the idle frame is off-centre by ${Math.round(mid - fw / 2)}px`);
    }
  } else {
    for (let r = 0; r < 4; r++) {
      const f = info(0, r);
      if (!f.n) continue;
      if (e.layer === 'body') {
        if (Math.abs(f.y1 - FEET_ROW) > 1) add('error', 'alignment', `row ${r}: feet are on row ${f.y1}, they must be on row ${FEET_ROW} so layers stack`);
        if (Math.abs((f.x0 + f.x1) / 2 - FRAME_W / 2) > 3) add('error', 'alignment', `row ${r}: the body is off-centre (centre column ${(f.x0 + f.x1) / 2}, expected ${FRAME_W / 2})`);
      } else if (f.y1 > FEET_ROW + 1 && e.layer !== 'weapon' && e.layer !== 'cape') add('error', 'alignment', `row ${r}: the layer extends below the feet line (row ${f.y1} > ${FEET_ROW})`);
      else if (e.layer !== 'weapon' && e.layer !== 'cape' && (f.x0 < 8 || f.x1 > FRAME_W - 9)) add('error', 'alignment', `row ${r}: the ${e.layer} layer is far from the body (columns ${f.x0} to ${f.x1}); layers must share the 48x48 grid of the body sheet`);
    }
  }
  return out;
}

/** Validates a directory containing manifest.json and the sheets it lists. */
export function validateDir(dir: string): { findings: Finding[]; entries: SheetEntry[]; ok: SheetEntry[]; records: AssetRecord[] } {
  const records: AssetRecord[] = [];
  const findings: Finding[] = [], ok: SheetEntry[] = [], mf = path.join(dir, 'manifest.json');
  if (!fs.existsSync(mf)) return { findings: [{ file: 'manifest.json', level: 'error', rule: 'manifest', msg: 'manifest.json not found' }], entries: [], ok, records };
  let m: Manifest;
  try {
    m = JSON.parse(fs.readFileSync(mf, 'utf8'));
  } catch (e) {
    return { findings: [{ file: 'manifest.json', level: 'error', rule: 'manifest', msg: `not valid JSON: ${(e as Error).message}` }], entries: [], ok, records };
  }
  if (m.version !== 1 || !Array.isArray(m.sheets)) return { findings: [{ file: 'manifest.json', level: 'error', rule: 'manifest', msg: 'expected { "version": 1, "sheets": [...] }' }], entries: [], ok, records };
  const seen = new Set<string>();
  for (const e of m.sheets) {
    const before = findings.length;
    const fail = (rule: Finding['rule'], msg: string) => findings.push({ file: String((e as any)?.file ?? '?'), level: 'error', rule, msg });
    if (!e || typeof e.file !== 'string' || !ENTRY_TYPES.includes(e.type)) { fail('manifest', `entry needs "type" (${ENTRY_TYPES.join(', ')}) and "file"`); continue; }
    if (e.file.includes('..') || path.isAbsolute(e.file)) { fail('manifest', 'file paths must stay inside the asset folder'); continue; }
    const key = entryKey(e);
    if (seen.has(key)) { fail('manifest', `duplicate asset id: "${key}" is listed twice`); continue; }
    if (!e.file.toLowerCase().endsWith('.png')) { fail('format', `unsupported format "${path.extname(e.file) || 'none'}": images must be PNG`); continue; }
    seen.add(key);
    const full = path.join(dir, e.file);
    if (!fs.existsSync(full)) { fail('manifest', 'missing file: not found'); continue; }
    let img: Image;
    try {
      img = decodePng(fs.readFileSync(full));
    } catch (err) {
      fail('format', (err as Error).message);
      continue;
    }
    findings.push(...validateSheet(e, img));
    if (!findings.slice(before).some((f) => f.level === 'error')) {
      ok.push(e);
      records.push(describe(e, img));
    }
  }
  // unlisted PNG files are a mistake more often than not
  const listed = new Set(m.sheets.map((e) => e?.file));
  const walk = (d: string, rel = ''): string[] => fs.readdirSync(d, { withFileTypes: true }).flatMap((f) => (f.isDirectory() ? walk(path.join(d, f.name), `${rel}${f.name}/`) : f.name.endsWith('.png') ? [`${rel}${f.name}`] : []));
  for (const f of walk(dir)) if (!listed.has(f)) findings.push({ file: f, level: 'warning', rule: 'manifest', msg: 'PNG is not listed in manifest.json and will not be loaded' });
  return { findings, entries: m.sheets, ok, records };
}
