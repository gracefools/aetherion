// Renders the TEMPORARY placeholder audio and writes assets/audio (OGG Vorbis + manifest.json).
//
//   npm run audio:build                     everything
//   npm run audio:build -- BGM-002 ui.click   only these ids (the rest of the manifest is kept)
//   npm run audio:build -- --wav <dir>      also keep the 16-bit WAV masters in <dir>
//
// Needs ffmpeg on the PATH for the OGG encoding (the dev image has it: deploy/Dockerfile.dev).
// The output is deterministic, so the masters can always be regenerated from this code.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { AUDIO_DEFS, type AudioDef } from '../../shared/src/audio';
import { levels, SR, wav, type Stereo } from './dsp';
import { oggInfo, type AudioEntry, type AudioManifest } from './manifest';
import { MUSIC } from './music';
import { AMBIENCE, renderSfx, SFX, SFX_GAIN } from './sfx';

const OUT = 'assets/audio';
const args = process.argv.slice(2);
const wavAt = args.indexOf('--wav'), wavDir = wavAt >= 0 ? args.splice(wavAt, 2)[1] : '';
const only = new Set(args);
const today = new Date().toISOString().slice(0, 10);

if (spawnSync('ffmpeg', ['-version'], { encoding: 'utf8' }).status !== 0) {
  console.error('ffmpeg was not found. It is needed to encode OGG files. Run this inside the dev image (deploy/Dockerfile.dev) or install ffmpeg.');
  process.exit(1);
}
const unknown = [...only].filter((id) => !AUDIO_DEFS.some((d) => d.id === id));
if (unknown.length) {
  console.error(`unknown asset id: ${unknown.join(', ')}`);
  process.exit(1);
}

const PROVIDER = 'procedural-placeholder';
const NOTICE =
  'TEMPORARY PLACEHOLDER AUDIO. Every file listed here with "temporary": true was synthesised by this project\'s own code (scripts/audio) because the Suno MCP ' +
  'integration required by the M10 specification was not available. None of it was generated by Suno or by any other music service, and none of it has been ' +
  'reviewed or cleared for commercial release. Replace the files and update each entry (provider, source, generated, license, temporary) when real tracks exist.';
const sourceOf = (d: AudioDef) =>
  d.category === 'music'
    ? 'Composed as note data in scripts/audio/music.ts and rendered by the software synthesiser in scripts/audio/dsp.ts. No samples, recordings, reference tracks or third-party audio.'
    : 'Synthesised from noise and oscillators by scripts/audio/sfx.ts (synthesiser: scripts/audio/dsp.ts). No samples, recordings or third-party audio.';
const LICENSE =
  'Original work generated by this project\'s source code; no third-party material, so no third-party licence applies. Temporary stand-in: NOT a Suno track, ' +
  'not reviewed by a rights holder or lawyer, and not cleared for commercial release.';

function render(d: AudioDef): Stereo {
  if (d.category === 'music') return MUSIC[d.id]();
  if (d.category === 'ambience') return AMBIENCE[d.id]();
  return renderSfx(d.id);
}
const missing = AUDIO_DEFS.filter((d) => !(d.category === 'music' ? MUSIC[d.id] : d.category === 'ambience' ? AMBIENCE[d.id] : SFX[d.id]));
if (missing.length) {
  console.error(`no renderer for: ${missing.map((d) => d.id).join(', ')}`);
  process.exit(1);
}

let old: AudioManifest | null = null;
try {
  old = JSON.parse(fs.readFileSync(path.join(OUT, 'manifest.json'), 'utf8'));
} catch { /* first build */ }
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'aeth-audio-'));
const assets: AudioEntry[] = [];
let bytes = 0;
const t0 = Date.now();
for (const d of AUDIO_DEFS) {
  const file = `${d.path}.ogg`, dst = path.join(OUT, file);
  const kept = old?.assets.find((e) => e.id === d.id);
  if (only.size && !only.has(d.id) && kept && fs.existsSync(dst)) {
    assets.push(kept);
    bytes += fs.statSync(dst).size;
    continue;
  }
  const started = Date.now(), audio = render(d), lv = levels(audio);
  for (let i = 0; i < audio.l.length; i++) if (!Number.isFinite(audio.l[i]) || !Number.isFinite(audio.r[i])) throw new Error(`${d.id}: the renderer produced a non-finite sample`);
  const src = path.join(tmp, 'a.wav');
  fs.writeFileSync(src, wav(audio));
  if (wavDir) {
    fs.mkdirSync(path.dirname(path.join(wavDir, `${d.path}.wav`)), { recursive: true });
    fs.copyFileSync(src, path.join(wavDir, `${d.path}.wav`));
  }
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  // Vorbis quality 4 (about 128 kbit/s stereo) for music, 3 for ambience and effects.
  const r = spawnSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', src, '-map_metadata', '-1', '-c:a', 'libvorbis', '-q:a', d.category === 'music' ? '4' : '3',
    '-metadata', `title=${d.title}`, '-metadata', 'comment=Aetherion Online temporary placeholder audio (procedurally synthesised; not final)', '-fflags', '+bitexact', '-flags:a', '+bitexact', dst], { encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`ffmpeg failed for ${d.id}: ${r.stderr}`);
  const info = oggInfo(fs.readFileSync(dst));
  // the encoded length must equal the rendered length, or loops would click
  if (Math.abs(info.duration - audio.l.length / SR) > 0.002) throw new Error(`${d.id}: encoded ${info.duration}s but rendered ${audio.l.length / SR}s`);
  bytes += fs.statSync(dst).size;
  assets.push({
    id: d.id, file, category: d.category, title: d.title, duration: Math.round(info.duration * 1000) / 1000, loop: d.loop,
    gain: d.category === 'sfx' ? SFX_GAIN[d.id] ?? 0.6 : 1, trigger: d.trigger, assoc: d.assoc,
    ...(d.location ? { location: d.location } : {}), ...(d.mood ? { mood: d.mood } : {}), ...(d.reserved ? { reserved: d.reserved } : {}),
    channels: info.channels, sampleRate: info.sampleRate, peakDb: Math.round(lv.peakDb * 10) / 10, rmsDb: Math.round(lv.rmsDb * 10) / 10,
    provider: PROVIDER, source: sourceOf(d), generated: today, license: LICENSE, temporary: true,
  });
  console.log(`${d.id.padEnd(26)} ${info.duration.toFixed(2).padStart(6)}s  ${info.channels}ch  peak ${lv.peakDb.toFixed(1).padStart(5)} dB  rms ${lv.rmsDb.toFixed(1).padStart(5)} dB  ${(fs.statSync(dst).size / 1024).toFixed(0).padStart(4)} kB  (${Date.now() - started} ms)`);
}
fs.rmSync(tmp, { recursive: true, force: true });
const manifest: AudioManifest = { version: 1, generated: today, notice: NOTICE, assets };
fs.writeFileSync(path.join(OUT, 'manifest.json'), JSON.stringify(manifest, null, 1) + '\n');
console.log(`${assets.length} assets, ${(bytes / 1048576).toFixed(2)} MB, in ${((Date.now() - t0) / 1000).toFixed(1)} s -> ${OUT}/manifest.json`);
