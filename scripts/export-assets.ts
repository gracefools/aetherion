// Exports the built-in art as PNG templates (assets/templates) in exactly the layout the importer
// expects, so an artist can paint over real sheets. Runs the client code in headless Chromium.
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright-core';
import { createApp } from '../server/src/app';
import { config } from '../server/src/config';

const out = process.argv[2] ?? 'assets/templates';
const app = await createApp({ ...config, host: '127.0.0.1' });
const base = `http://127.0.0.1:${await app.listen(0)}`;
const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  await page.addInitScript(() => { (window as any).__name = (f: any) => f; });
  await page.goto(base);
  await page.waitForFunction(() => (window as any).__art);
  const sheets = await page.evaluate(() => {
    const A = (window as any).__art, res: { entry: any; url: string }[] = [];
    const opaque = (c: HTMLCanvasElement) => { const d = c.getContext('2d')!.getImageData(0, 0, c.width, c.height).data; for (let i = 3; i < d.length; i += 4) if (d[i]) return true; return false; };
    for (const id of A.MONSTER_TYPES) res.push({ entry: { type: 'monster', id, file: `monsters/${id}.png`, scale: A.monsterScale(id) }, url: A.getMonsterSheet(id).toDataURL() });
    for (const id of A.PROP_KINDS) res.push({ entry: { type: 'prop', id, file: `props/${id}.png` }, url: A.propSprite(id).toDataURL() });
    for (const job of ['knight', 'mage', 'ranger', 'assassin', 'cleric', 'berserker'])
      for (const layer of A.LAYERS) {
        const c = A.renderSheet(A.defaultAppearance(job), job, layer);
        if (opaque(c)) res.push({ entry: { type: 'character', layer, item: `${job}_default`, file: `${layer}/${job}_default.png` }, url: c.toDataURL() });
      }
    // M12: every skill, passive, status, weapon-attack and rune icon
    for (const ic of A.iconManifest()) res.push({ entry: { type: 'icon', kind: ic.kind, id: ic.ref, file: ic.file }, url: A.iconCanvas(ic.id).toDataURL() });
    return res;
  });
  const icons = await page.evaluate(() => (window as any).__art.iconManifest());
  fs.rmSync(out, { recursive: true, force: true });
  for (const s of sheets) {
    fs.mkdirSync(path.dirname(path.join(out, s.entry.file)), { recursive: true });
    fs.writeFileSync(path.join(out, s.entry.file), Buffer.from(s.url.split(',')[1], 'base64'));
  }
  const meta = { source: 'Built-in art generated by this project\'s code (client/src/game); exported as a template to paint over.', license: 'Project-owned original; no third-party material.' };
  fs.writeFileSync(path.join(out, 'manifest.json'), JSON.stringify({ version: 1, sheets: sheets.map((s) => ({ ...s.entry, ...meta })) }, null, 1));
  // the skill icon manifest: which image belongs to which skill, status, weapon attack and rune
  fs.writeFileSync(path.join(out, 'icons', 'icons.json'), JSON.stringify({ version: 1, size: 64, icons }, null, 1));
  console.log(`exported ${sheets.length} sheets to ${out}`);
} finally {
  await browser.close();
  await app.close();
}
